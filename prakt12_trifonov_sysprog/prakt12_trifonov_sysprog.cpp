#include <string>
#include <iostream>
using namespace std;

bool CheckNums(int n) {
    string s = to_string(abs(n));
    return s.front() == s.back();
}

int main(int argc, char* argv[])
{
    if (argc < 3) {
        cout << "Error: ne peredan diapozon" << endl;
        system("pause");
        return 1;
    }

    int a = stoi(argv[1]);
    int b = stoi(argv[2]);

    if (a > b) {
        int temp = a;
        a = b;
        b = temp;
    }

    int count = 0;
    cout << "prakt12" << endl;
    for (int i = a; i <= b; i++) {
        if (CheckNums(i)) {
            cout << i << " ";
            count++;
        }
    }
    cout << "All finded numbers: " << count << endl;
    system("pause");
}

